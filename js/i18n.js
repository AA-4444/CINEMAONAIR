function getLang() {
  return localStorage.getItem('cinemaua_lang') || 'ua';
}

function setLang(lang) {
  localStorage.setItem('cinemaua_lang', lang);
  applyLang();
}

function toggleLang() {
  setLang(getLang() === 'ua' ? 'en' : 'ua');
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || (I18N.ua[key]) || key;
}

function applyLang() {
  const lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  // Update lang button label
  document.querySelectorAll('.lang-btn span').forEach(el => {
    el.textContent = lang === 'ua' ? 'UA' : 'EN';
  });
  document.documentElement.lang = lang === 'ua' ? 'uk' : 'en';
}

// ========== Fix static file navigation ==========
// Rewrites absolute paths (/movies, /movie/1, etc.) to relative .html paths
// so templates work as standalone static files without a backend server.
function fixNavLinks() {
  document.querySelectorAll('a[href]').forEach(a => {
    let h = a.getAttribute('href');
    if (!h || h.startsWith('http') || h.startsWith('#') || h.startsWith('javascript') || h.endsWith('.html') || h.includes('.html?')) return;

    // Route mapping
    if (h === '/') { a.href = 'index.html'; return; }
    if (h === '/movies' || h.startsWith('/movies?')) { a.href = h.replace('/movies', 'catalog.html?type=movie').replace('?type=movie?', '?type=movie&'); return; }
    if (h === '/series' || h.startsWith('/series?')) { a.href = h.replace('/series', 'catalog.html?type=series').replace('?type=series?', '?type=series&'); return; }
    if (h === '/cartoons' || h.startsWith('/cartoons?')) { a.href = h.replace('/cartoons', 'catalog.html?type=cartoon').replace('?type=cartoon?', '?type=cartoon&'); return; }
    if (h === '/anime' || h.startsWith('/anime?')) { a.href = h.replace('/anime', 'catalog.html?type=anime').replace('?type=anime?', '?type=anime&'); return; }
    if (h === '/categories') { a.href = 'categories.html'; return; }
    if (h.startsWith('/categories/')) { a.href = 'catalog.html?genre=' + h.split('/').pop(); return; }

    // Dynamic routes: /movie/123 → movie.html?id=123
    const movieMatch = h.match(/^\/movie\/(\d+)/);
    if (movieMatch) { a.href = 'movie.html?id=' + movieMatch[1]; return; }

    // /watch/123?s=1&e=2 → watch.html?id=123&s=1&e=2
    const watchMatch = h.match(/^\/watch\/(\d+)(.*)/);
    if (watchMatch) { a.href = 'watch.html?id=' + watchMatch[1] + (watchMatch[2] ? watchMatch[2].replace('?', '&') : ''); return; }

    // /search → search.html
    if (h === '/search' || h.startsWith('/search?')) { a.href = h.replace('/search', 'search.html'); return; }
  });

  // Fix form actions
  document.querySelectorAll('form[action]').forEach(f => {
    let a = f.getAttribute('action');
    if (a === '/search') f.action = 'search.html';
  });
}

document.addEventListener('DOMContentLoaded', () => {
  applyLang();
  fixNavLinks();
});
